//! Small, dependency-free records for repeatable baseline measurements.
//!
//! The harness deliberately measures scalar implementations rather than claiming
//! production performance. Consumers can write [`BenchmarkRecord`] values as
//! ScanBench-compatible JSON lines without a serialization dependency.

/// A minimal ScanBench-compatible baseline measurement.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BenchmarkRecord {
    /// Schema revision expected by `benchmarks/schema/scanbench-record.schema.json`.
    pub schema_version: u32,
    /// Stable synthetic or provenance-controlled sample identifier.
    pub sample_id: String,
    /// Hash or declaration of the input fixture.
    pub sample_hash: String,
    /// Domain label. MP2 uses `generic`.
    pub domain: String,
    /// Device/runtime class that produced the sample.
    pub device_class: String,
    /// Operation measured by the harness.
    pub operation: String,
    /// Number of measured loop iterations.
    pub iterations: u64,
    /// Aggregate elapsed wall-clock time in nanoseconds.
    pub elapsed_nanoseconds: u128,
}

impl BenchmarkRecord {
    /// Creates a baseline record for a deterministic generated fixture.
    pub fn synthetic_baseline(
        domain: impl Into<String>,
        sample_id: impl Into<String>,
        operation: impl Into<String>,
        iterations: u64,
        elapsed_nanoseconds: u128,
    ) -> Self {
        Self {
            schema_version: 1,
            sample_id: sample_id.into(),
            sample_hash: "generated-deterministic-fixture".into(),
            domain: domain.into(),
            device_class: "host-scalar".into(),
            operation: operation.into(),
            iterations,
            elapsed_nanoseconds,
        }
    }

    /// Creates a synthetic-host benchmark record for one named operation.
    pub fn scalar_baseline(
        operation: impl Into<String>,
        iterations: u64,
        elapsed_nanoseconds: u128,
    ) -> Self {
        Self::synthetic_baseline(
            "generic",
            "mp2-inline-synthetic",
            operation,
            iterations,
            elapsed_nanoseconds,
        )
    }

    /// Emits one compact JSON line conforming to the MP1 ScanBench envelope.
    ///
    /// Fields are generated by the in-tree harness and contain no user-provided
    /// strings, so this dependency-free serializer is intentionally narrow.
    pub fn to_json_line(&self) -> String {
        format!(
            concat!(
                r#"{{"schema_version":{},"sample_id":"{}","sample_hash":"{}","#,
                r#""domain":"{}","device_class":"{}","metrics":{{"#,
                r#""operation":"{}","iterations":{},"elapsed_nanoseconds":{}}}}}"#
            ),
            self.schema_version,
            self.sample_id,
            self.sample_hash,
            self.domain,
            self.device_class,
            self.operation,
            self.iterations,
            self.elapsed_nanoseconds,
        )
    }
}

#[cfg(test)]
mod tests {
    use super::BenchmarkRecord;

    #[test]
    fn record_keeps_the_schema_envelope() {
        let line = BenchmarkRecord::scalar_baseline("crop", 2, 30).to_json_line();
        assert!(line.contains("\"schema_version\":1"));
        assert!(line.contains("\"operation\":\"crop\""));
    }
}
